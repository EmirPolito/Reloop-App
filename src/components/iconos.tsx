/* -------------------------------------------------------------------------- */
/*  Selector por nombre (para la barra de navegación)                         */
/* -------------------------------------------------------------------------- */

export const NavigationIcon = React.memo(function NavigationIcon({
  name,
  selected = false,
  color,
  size = 20,
}: {
  name: IconName | "favorite" | "add";
  selected?: boolean;
  color: string;
  size?: number;
}) {
  const icon = String(name);

  if (icon === "add") return <AgregarIcon size={size} color={color} />;

  if (icon === "home") {
    return selected ? (
      <InicioActivoIcon size={size} color={color} />
    ) : (
      <InicioInactivoIcon size={size} color={color} />
    );
  }

  if (icon === "star" || icon === "favorite") {
    return selected ? (
      <CorazonActivoIcon size={size} color={color} />
    ) : (
      <CorazonInactivoIcon size={size} color={color} />
    );
  }

  if (icon === "chat") {
    return selected ? (
      <ChatActivoIcon size={size} color={color} />
    ) : (
      <ChatInactivoIcon size={size} color={color} />
    );
  }

  if (icon === "person" || icon === "profile") {
    return selected ? (
      <PerfilActivoIcon size={size} color={color} />
    ) : (
      <PerfilInactivoIcon size={size} color={color} />
    );
  }

  return null;
});
